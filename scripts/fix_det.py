from pathlib import Path


def sub(rel, pairs):
    p = Path(rel)
    s = p.read_text(encoding="utf-8")
    for a, b in pairs:
        assert a in s, a
        s = s.replace(a, b, 1)
    p.write_text(s, encoding="utf-8", newline="")


